"""Regenerate the skills catalog in README.md / README.zh-CN.md.

Skills are discovered from top-level folders that contain a SKILL.md, then
classified and summarized using catalog.yml. Only the blocks between
``<!-- BEGIN:<block> -->`` and ``<!-- END:<block> -->`` are rewritten, so the
rest of each README stays hand-written.

Usage:
    uv run scripts/sync_readme.py          # update READMEs in place
    uv run scripts/sync_readme.py --check  # exit 1 if READMEs are stale (CI)
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from urllib.parse import quote

import yaml

ROOT = Path(__file__).resolve().parent.parent
CATALOG_PATH = ROOT / "catalog.yml"
READMES = {"en": ROOT / "README.md", "zh": ROOT / "README.zh-CN.md"}
FALLBACK_CATEGORY = "other"
SUMMARY_MAX_LEN = 90

TEXT = {
    "zh": {
        "skill": "技能",
        "summary": "简介",
        "features": "特性",
        "category": "分类",
        "count": "数量",
        "scripts": "⚙️ 脚本",
        "api_key": "🔑 需 Key",
        "prompt_only": "📝 纯提示",
        "generated": "本区块由 scripts/sync_readme.py 自动生成，请勿手改",
        "badge_skills": "技能",
        "badge_categories": "分类",
    },
    "en": {
        "skill": "Skill",
        "summary": "Summary",
        "features": "Features",
        "category": "Category",
        "count": "Count",
        "scripts": "⚙️ Scripts",
        "api_key": "🔑 API key",
        "prompt_only": "📝 Prompt-only",
        "generated": "Auto-generated by scripts/sync_readme.py — do not edit by hand",
        "badge_skills": "skills",
        "badge_categories": "categories",
    },
}


@dataclass
class Category:
    id: str
    emoji: str
    name: dict[str, str]
    desc: dict[str, str]
    aliases: list[str]
    keywords: list[str]


@dataclass
class Skill:
    dir: str
    name: str
    description: str
    category: str = FALLBACK_CATEGORY
    category_source: str = "fallback"
    summary: dict[str, str] = field(default_factory=dict)
    summary_from_catalog: bool = False
    has_scripts: bool = False
    api_key: bool = False


def load_catalog() -> tuple[list[Category], dict[str, dict]]:
    data = yaml.safe_load(CATALOG_PATH.read_text(encoding="utf-8")) or {}
    categories = [
        Category(
            id=c["id"],
            emoji=c.get("emoji", ""),
            name=c["name"],
            desc=c.get("desc", {}),
            aliases=[a.lower() for a in c.get("aliases") or []],
            keywords=[k.lower() for k in c.get("keywords") or []],
        )
        for c in data.get("categories") or []
    ]
    if not any(c.id == FALLBACK_CATEGORY for c in categories):
        raise SystemExit(f"catalog.yml must define a '{FALLBACK_CATEGORY}' category")
    return categories, data.get("skills") or {}


def read_frontmatter(path: Path) -> dict:
    text = path.read_text(encoding="utf-8-sig")
    match = re.match(r"---\s*\n(.*?)\n---\s*(\n|$)", text, re.S)
    if not match:
        return {}
    try:
        return yaml.safe_load(match.group(1)) or {}
    except yaml.YAMLError as exc:
        print(f"⚠️  {path.relative_to(ROOT)}: invalid frontmatter ({exc})", file=sys.stderr)
        return {}


def first_sentence(text: str) -> str:
    text = " ".join(text.split())
    sentence = re.split(r"(?<=[。！？])|(?<=[.!?])\s", text, maxsplit=1)[0].strip()
    if len(sentence) > SUMMARY_MAX_LEN:
        sentence = sentence[: SUMMARY_MAX_LEN - 1].rstrip() + "…"
    return sentence


def classify(skill: Skill, meta: dict, entry: dict, categories: list[Category]) -> None:
    ids = {c.id for c in categories}
    if entry.get("category"):
        if entry["category"] not in ids:
            raise SystemExit(f"catalog.yml: unknown category '{entry['category']}' for {skill.dir}")
        skill.category, skill.category_source = entry["category"], "catalog"
        return

    nested = meta.get("metadata") if isinstance(meta.get("metadata"), dict) else {}
    fm_category = str(meta.get("category") or nested.get("category") or "").strip().lower()
    for cat in categories:
        if fm_category and (fm_category == cat.id or fm_category in cat.aliases):
            skill.category, skill.category_source = cat.id, "frontmatter"
            return

    tags = meta.get("tags") or nested.get("tags") or []
    haystack = " ".join([skill.dir, skill.name, skill.description, fm_category, *map(str, tags)]).lower()
    scores = {c.id: sum(kw in haystack for kw in c.keywords) for c in categories}
    best = max(scores, key=scores.get)
    if scores[best] > 0:
        skill.category, skill.category_source = best, "keywords"


def discover(categories: list[Category], entries: dict[str, dict]) -> list[Skill]:
    skills, seen = [], set()
    for skill_md in sorted(ROOT.glob("*/SKILL.md")):
        folder = skill_md.parent
        if folder.name.startswith("."):
            continue
        seen.add(folder.name)
        entry = entries.get(folder.name) or {}
        if entry.get("hidden"):
            continue
        meta = read_frontmatter(skill_md)
        skill = Skill(
            dir=folder.name,
            name=str(meta.get("name") or folder.name),
            description=str(meta.get("description") or ""),
            has_scripts=(folder / "scripts").is_dir() or any(folder.glob("*.py")),
            api_key=bool(entry.get("api_key")) or (folder / ".env.example").exists(),
        )
        classify(skill, meta, entry, categories)
        summary = entry.get("summary") or {}
        fallback = first_sentence(skill.description) or skill.name
        skill.summary = {"zh": summary.get("zh") or fallback, "en": summary.get("en") or fallback}
        skill.summary_from_catalog = bool(summary.get("zh") and summary.get("en"))
        skills.append(skill)

    for stale in sorted(set(entries) - seen):
        print(f"⚠️  catalog.yml lists '{stale}' but no {stale}/SKILL.md exists", file=sys.stderr)
    return skills


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def features(skill: Skill, lang: str) -> str:
    t = TEXT[lang]
    tags = [t["scripts"]] if skill.has_scripts else [t["prompt_only"]]
    if skill.api_key:
        tags.append(t["api_key"])
    return " · ".join(tags)


def grouped(skills: list[Skill], categories: list[Category]) -> list[tuple[Category, list[Skill]]]:
    groups = []
    for cat in categories:
        members = sorted((s for s in skills if s.category == cat.id), key=lambda s: s.name.lower())
        if members:
            groups.append((cat, members))
    return groups


def render_badges(skills: list[Skill], groups: list, lang: str) -> str:
    t = TEXT[lang]

    def badge(label: str, value: int, color: str) -> str:
        return f"![{label}](https://img.shields.io/badge/{quote(label)}-{value}-{color}?style=flat-square)"

    return " ".join([badge(t["badge_skills"], len(skills), "6366f1"), badge(t["badge_categories"], len(groups), "0ea5e9")])


def render_overview(groups: list, lang: str) -> str:
    t = TEXT[lang]
    lines = [f"| {t['category']} | {t['count']} | {t['skill']} |", "|---|:---:|---|"]
    for cat, members in groups:
        names = " ".join(f"`{s.name}`" for s in members)
        lines.append(f"| {cat.emoji} [{cat.name[lang]}](#cat-{cat.id}) | {len(members)} | {names} |")
    return "\n".join(lines)


def render_catalog(groups: list, lang: str) -> str:
    t = TEXT[lang]
    parts = []
    for cat, members in groups:
        parts.append(f'<a id="cat-{cat.id}"></a>\n\n### {cat.emoji} {cat.name[lang]}\n')
        if cat.desc.get(lang):
            parts.append(f"> {cat.desc[lang]}\n")
        parts.append(f"| {t['skill']} | {t['summary']} | {t['features']} |\n|---|---|---|")
        for s in members:
            parts.append(f"| [**{cell(s.name)}**](./{quote(s.dir)}/) | {cell(s.summary[lang])} | {features(s, lang)} |")
        parts.append("")
    return "\n".join(parts).rstrip()


def replace_block(text: str, block: str, body: str, path: Path, lang: str) -> str:
    pattern = re.compile(rf"(<!-- BEGIN:{block} -->)(.*?)(<!-- END:{block} -->)", re.S)
    if not pattern.search(text):
        raise SystemExit(f"{path.name}: missing <!-- BEGIN:{block} --> / <!-- END:{block} --> markers")
    note = f"<!-- {TEXT[lang]['generated']} -->"
    return pattern.sub(lambda m: f"{m.group(1)}\n{note}\n{body}\n{m.group(3)}", text, count=1)


def report(skills: list[Skill]) -> None:
    pending = [s for s in skills if s.category_source != "catalog" or not s.summary_from_catalog]
    print(f"✔ {len(skills)} skills synced")
    if not pending:
        return
    print("\nℹ️  These skills are not fully registered in catalog.yml (auto-guessed for now).")
    print("   Paste and refine the stub below under `skills:` — or ask an AI to do it per AGENTS.md:\n")
    for s in pending:
        print(f"  {s.dir}:  # category guessed by {s.category_source}")
        print(f"    category: {s.category}")
        print("    summary:")
        print(f"      zh: {s.summary['zh']}")
        print(f"      en: {s.summary['en']}")
        print()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if READMEs are out of date")
    args = parser.parse_args()

    categories, entries = load_catalog()
    skills = discover(categories, entries)
    groups = grouped(skills, categories)

    stale = []
    for lang, path in READMES.items():
        original = path.read_text(encoding="utf-8")
        updated = original
        for block, body in (
            ("badges", render_badges(skills, groups, lang)),
            ("overview", render_overview(groups, lang)),
            ("catalog", render_catalog(groups, lang)),
        ):
            updated = replace_block(updated, block, body, path, lang)
        if updated != original:
            stale.append(path.name)
            if not args.check:
                path.write_text(updated, encoding="utf-8", newline="\n")

    if args.check:
        if stale:
            print(f"✘ Out of date: {', '.join(stale)}. Run: uv run scripts/sync_readme.py")
            return 1
        print("✔ READMEs are up to date")
        return 0

    report(skills)
    print(f"Updated: {', '.join(stale)}" if stale else "READMEs already up to date")
    return 0


if __name__ == "__main__":
    for stream in (sys.stdout, sys.stderr):
        stream.reconfigure(encoding="utf-8")
    sys.exit(main())
